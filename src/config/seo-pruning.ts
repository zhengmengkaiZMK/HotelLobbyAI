const goneSet = new Set(SEO_GONE_SLUGS);

export type PruneDecision =
  | { type: 'gone' }
  | { type: 'redirect'; to: string }
  | null;

/**
 * @param slug a slug, or a path with a leading slash. Both are accepted so the
 *   same helper works in middleware (pathname) and in JSX link lists (href).
 */
export function getPruneDecision(slug: string): PruneDecision {
  const key = slug.replace(/^\/+/, '').replace(/\/+$/, '');
  if (!key) return null;
  if (goneSet.has(key)) return { type: 'gone' };
  const to = SEO_REDIRECTS[key];
  // `to` may be '' (= the homepage); only undefined means "not pruned".
  if (to !== undefined) return { type: 'redirect', to };
  return null;
}

/** True when the page must stay out of the sitemap. */
export function isPrunedPath(path: string): boolean {
  return getPruneDecision(path) !== null;
}
